const BK_EVERY = 7 * 864e5;

window.GUIDE = (() => {
  const now = () => window.DVORYK_NOW || Date.now();
  const busyUI = () => $("modal").classList.contains("show") || $("dialog").classList.contains("show");
  const row = (ic, t, txt) => `<details class="gd-row"><summary><span class="gd-ic">${ic}</span><b>${t}</b></summary><p>${txt}</p></details>`;
  const lock = (t, when) => `<div class="gd-row gd-lock"><span class="gd-ic">🔒</span><b>${t}</b><small>${when}</small></div>`;
  function sec(title, body, n) { return `<div class="gd-sec"><div class="gd-h">${title}${n ? ` <small>${n}</small>` : ""}</div>${body}</div>`; }

  function open() {
    let html = sec(tt`Основи`, GUIDE_BASICS.map(r => row(...r)).join(""));
    if (window.UNL && typeof UNLOCKS !== "undefined") {
      const got = UNLOCKS.filter(u => UNL.on(u.id)), rest = UNLOCKS.filter(u => !UNL.on(u.id)).sort((a, b) => a.lvl - b.lvl);
      html += sec(tt`Город і село`, got.map(u => row(u.id === "cat" && typeof CAT_ICON !== "undefined" ? CAT_ICON : u.icon, u.title, u.text)).join("") +
        (rest.length ? lock(tt`Ще ${rest.length} — попереду`, tt`найближче на рівні ${rest[0].lvl}`) : ""), tt`${got.length} з ${UNLOCKS.length}`);
    }
    const w = S.wood;
    if (w && S.love && S.love.stage >= 4) {
      const got = GUIDE_WOOD.filter(r => r[3](w)), next = GUIDE_WOOD.find(r => !r[3](w) && r[4]);
      html += sec(tt`Майстерня`, got.map(r => row(r[0], r[1], r[2])).join("") + (next ? lock(next[1].split(":")[0], tt`після ${next[4]} виробів (зараз ${w.done})`) : ""));
    } else if (S.level >= 8) html += sec(tt`Майстерня`, lock(tt`Майстерня`, tt`відкриється пізніше — за сюжетом 💛`));
    modal({ title: tt`Довідник господині 📖`, html: `<div class="gd-list">${gx(html)}</div>`, buttons: [{ label: tt`Зрозуміло 💛` }] });
  }

  /* ---------- нагадування зберегти прогрес ---------- */
  function exported() { S.bkAt = now(); save(); }
  function daysAgo() { return S.bkAt ? Math.floor((now() - S.bkAt) / 864e5) : null; }
  function note() {
    const d = daysAgo();
    return d == null ? tt`Код прогресу ще не зберігався.` : d === 0 ? tt`Востаннє збережено сьогодні.` : tt`Востаннє збережено ${d} ${d % 10 === 1 && d % 100 !== 11 ? tt`день` : [2, 3, 4].includes(d % 10) && ![12, 13, 14].includes(d % 100) ? tt`дні` : tt`днів`} тому.`;
  }
  let lastTry = 0;
  function tick() {
    if (!S || !S.started || S.tut < 4 || S.level < 3 || busyUI() || Date.now() - lastTry < 20e3) return;
    lastTry = Date.now();
    if (!S.bkAsk) { S.bkAsk = now(); save(); return; }               // відлік від першого запуску з цим оновленням
    if (now() - Math.max(S.bkAt || 0, S.bkAsk) < BK_EVERY) return;
    S.bkAsk = now(); save();
    modal({ title: tt`Час зберегти прогрес 💾`,
      html: tt`<div class="big-emoji">💾</div><p>${note()} На iPhone сховище браузера іноді очищається — а з кодом прогресу гру можна відновити будь-коли.</p><p class="hint-s">Збережи код у Нотатки чи надішли собі в месенджер — це хвилинка.</p>`,
      buttons: [{ label: tt`💾 Зберегти зараз`, onClick: () => showExport() },
        { label: tt`Нагадай завтра`, cls: "ghost", onClick: () => { S.bkAsk = now() - BK_EVERY + 864e5; save(); } }] });
  }
  return { open, tick, exported, note };
})();
