/* Карта мальованих картинок (емодзі → файл). Стоїть у кінці, щоб бачити всі ланцюжки, зокрема святкові. */
window.PAINTED = (() => {
  const k = s => [...s].filter(c => c !== "\uFE0F").map(c => c.codePointAt(0).toString(16)).join("-");
  const map = {};
  Object.entries({ ...UI_ICONS, ...DECO_ICONS }).forEach(([e, f]) => { map[k(e)] = "items/" + f + ".webp"; });
  PAINTED_ITEMS.forEach(id => {
    const [a, b] = id.split("-");
    const emoji = a === "gen" ? GENS[b] && GENS[b].icon : CHAINS[a] && CHAINS[a].items[+b] && CHAINS[a].items[+b][0];
    if (emoji) map[k(emoji)] = "items/" + id + ".webp";
  });
  return map;
})();
